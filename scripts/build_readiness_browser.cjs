"use strict";
/**
 * VOR-008 deterministic, dependency-free TypeScript to browser ESM emission.
 * Restricted exact transformations fail closed if VOR-007 TS structure changes.
 * Use node scripts/build_readiness_browser.cjs --check in CI to enforce parity.
 */
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const edits = (s, entries, file) => {
  for(const [from,to] of entries){
    if(!s.includes(from))throw Error("Unexpected VOR-007 source shape in "+file+": "+from);
    s=s.replace(from,to);
  }
  return s;
};
const header = "// GENERATED by scripts/build_readiness_browser.cjs from backend/readiness/*.ts\n// Do not hand-edit. Run generator then run VOR-008 parity tests.\n";
function questions(){
 const source=read("backend/readiness/questions.ts");
 const at=source.indexOf("export const ENGINE_VERSION");
 if(at<0)throw Error("VOR-007 version declaration missing");
 let s=source.slice(at);
 s=edits(s,[
  ["export const CATEGORIES: readonly Category[]", "export const CATEGORIES"],
  ["export const LOCALES: readonly Locale[]", "export const LOCALES"],
  ["export const ANSWERS: readonly Answer[]", "export const ANSWERS"],
  ["const l = (en: string, bn: string, hi: string): Localized =>", "const l = (en, bn, hi) =>"],
  ["export const CHOICES: Readonly<Record<Answer, Localized>>", "export const CHOICES"],
  ["export const HEADINGS: Readonly<Record<Category, Localized>>", "export const HEADINGS"],
  ["const common: readonly Question[]", "const common"],
  ["const categoryQuestions: Readonly<Record<Category, readonly Question[]>>", "const categoryQuestions"],
  ["export function questionsFor(category: Category): readonly Question[]", "export function questionsFor(category)"],
  ["export const DISCLAIMERS: Localized", "export const DISCLAIMERS"],
 ],"questions.ts");
 if(/\b(?:readonly|Readonly|Category\[\]|Locale\[\]|Answer\[\]|Localized)\b/.test(s))
  throw Error("Unexpected TS declarations remain in generated questions.js");
 return header+s.trimEnd()+"\n";
}
function engine(){
 const source=read("backend/readiness/engine.ts");
 const at=source.indexOf("const error =");
 if(at<0)throw Error("VOR-007 error declaration missing");
 let s=source.slice(at);
 s=edits(s,[
  ['const error = (code: EngineError["code"]): EngineError =>', "const error = (code) =>"],
  ["function object(v:unknown):v is Record<string, unknown>", "function object(v)"],
  ['export function getQuestionnaire(category:unknown, locale:unknown="en")', 'export function getQuestionnaire(category, locale="en")'],
  ["export function evaluateReadiness(raw:unknown):ChecklistResult|EngineError", "export function evaluateReadiness(raw)"],
  ["const unanswered:string[]=[],unsure:string[]=[],explanations:Explanation[]=[],next_steps:{question_id:string;suggestion:string}[]=[];", "const unanswered=[],unsure=[],explanations=[],next_steps=[];"],
 ],"engine.ts");
 s=s.replaceAll(" as Category","").replaceAll(" as Locale","")
    .replaceAll(" as Answer","").replaceAll(" as const","");
 if(/\bEngineError\b|\bChecklistResult\b|\bExplanation\b|:unknown/.test(s))
  throw Error("Unexpected TS types remain in generated engine.js");
 const imp='import { ANSWERS, CATEGORIES, CHOICES, DISCLAIMERS, ENGINE_VERSION, HEADINGS, LOCALES, questionsFor } from "./readiness-questions.js";\n';
 return header+imp+s.trimEnd()+"\n";
}
const outputs={
 "assets/readiness-questions.js":questions(),
 "assets/readiness-engine.js":engine(),
};
const check=process.argv.includes("--check");
for(const [file,content] of Object.entries(outputs)){
 if(check){
  if(!fs.existsSync(path.join(root,file))||read(file)!==content)
   throw Error(file+" differs from VOR-007 source; regenerate browser assets.");
 }else fs.writeFileSync(path.join(root,file),content,"utf8");
}
console.log("PASS: VOR-008 browser ESM matches VOR-007 TypeScript source (no external build dependency)");
